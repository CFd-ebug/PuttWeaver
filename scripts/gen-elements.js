#!/usr/bin/env node
// Generates src/data/elements.js, the table the Periodic Table game plays on.
//
// Everything here is plain fact written out by hand or derived by rule: IUPAC element names and symbols, the
// standard 18-column layout with the lanthanides and actinides as two separate rows, and the textbook family of
// each element. It is NOT copied from any dataset. Run `node scripts/gen-elements.js` to rewrite the output.
//
// Row format: [atomic number, symbol, name, column, row, family]
//   column 1..18, row 1..7 for the main table, rows 9 and 10 for the lanthanides and actinides.
const fs = require('fs'), path = require('path');

// ---- names and symbols, in atomic-number order (filled in below) ----
const SYMBOLS = [];
const NAMES = [];
const add = (pairs) => pairs.split(',').forEach(p => { const [s, n] = p.trim().split(' '); SYMBOLS.push(s); NAMES.push(n); });

// 1-30
add('H Hydrogen, He Helium, Li Lithium, Be Beryllium, B Boron, C Carbon, N Nitrogen, O Oxygen, F Fluorine, Ne Neon, ' +
    'Na Sodium, Mg Magnesium, Al Aluminum, Si Silicon, P Phosphorus, S Sulfur, Cl Chlorine, Ar Argon, K Potassium, Ca Calcium, ' +
    'Sc Scandium, Ti Titanium, V Vanadium, Cr Chromium, Mn Manganese, Fe Iron, Co Cobalt, Ni Nickel, Cu Copper, Zn Zinc');
// 31-60
add('Ga Gallium, Ge Germanium, As Arsenic, Se Selenium, Br Bromine, Kr Krypton, Rb Rubidium, Sr Strontium, Y Yttrium, Zr Zirconium, ' +
    'Nb Niobium, Mo Molybdenum, Tc Technetium, Ru Ruthenium, Rh Rhodium, Pd Palladium, Ag Silver, Cd Cadmium, In Indium, Sn Tin, ' +
    'Sb Antimony, Te Tellurium, I Iodine, Xe Xenon, Cs Cesium, Ba Barium, La Lanthanum, Ce Cerium, Pr Praseodymium, Nd Neodymium');
// 61-90
add('Pm Promethium, Sm Samarium, Eu Europium, Gd Gadolinium, Tb Terbium, Dy Dysprosium, Ho Holmium, Er Erbium, Tm Thulium, Yb Ytterbium, ' +
    'Lu Lutetium, Hf Hafnium, Ta Tantalum, W Tungsten, Re Rhenium, Os Osmium, Ir Iridium, Pt Platinum, Au Gold, Hg Mercury, ' +
    'Tl Thallium, Pb Lead, Bi Bismuth, Po Polonium, At Astatine, Rn Radon, Fr Francium, Ra Radium, Ac Actinium, Th Thorium');
// 91-118
add('Pa Protactinium, U Uranium, Np Neptunium, Pu Plutonium, Am Americium, Cm Curium, Bk Berkelium, Cf Californium, Es Einsteinium, Fm Fermium, ' +
    'Md Mendelevium, No Nobelium, Lr Lawrencium, Rf Rutherfordium, Db Dubnium, Sg Seaborgium, Bh Bohrium, Hs Hassium, Mt Meitnerium, Ds Darmstadtium, ' +
    'Rg Roentgenium, Cn Copernicium, Nh Nihonium, Fl Flerovium, Mc Moscovium, Lv Livermorium, Ts Tennessine, Og Oganesson');

// ---- layout ----
// Period lengths are 2, 8, 8, 18, 18, 32, 32; the table drops the f-block out into its own rows.
function place(z) {
  if (z === 1) return [1, 1];
  if (z === 2) return [18, 1];
  const periods = [[3, 10, 2], [11, 18, 3], [19, 36, 4], [37, 54, 5], [55, 86, 6], [87, 118, 7]];
  const [start, , row] = periods.find(([a, b]) => z >= a && z <= b);
  const k = z - start;                                   // 0-based position within the period
  if (row <= 3) return [k < 2 ? k + 1 : k + 11, row];     // 2 + 6 elements: columns 1-2, then 13-18
  if (row <= 5) return [k + 1, row];                      // 18 elements: columns 1-18
  if (k < 2) return [k + 1, row];                         // s block: columns 1-2
  if (k < 17) return [k + 1, row === 6 ? 9 : 10];         // 15 f-block elements: columns 3-17 of their own row
  return [k - 17 + 4, row];                               // remaining elements start under column 4
}

// ---- families ----
const NONMETAL = new Set([1, 6, 7, 8, 15, 16, 34]);
const METALLOID = new Set([5, 14, 32, 33, 51, 52]);
const POST_TRANSITION = new Set([13, 31, 49, 50, 81, 82, 83, 84, 113, 114, 115, 116]);
function family(z, col, row) {
  if (z >= 57 && z <= 71) return 'lan';
  if (z >= 89 && z <= 103) return 'act';
  if (NONMETAL.has(z)) return 'nonmetal';
  if (METALLOID.has(z)) return 'metalloid';
  if (POST_TRANSITION.has(z)) return 'post';
  if (col === 18) return 'noble';
  if (col === 17) return 'halogen';
  if (col === 1) return 'alkali';
  if (col === 2) return 'alkaline';
  return 'transition';
}

module.exports = { SYMBOLS, NAMES, place, family };

if (require.main === module) {
  if (SYMBOLS.length !== 118 || NAMES.length !== 118) throw new Error('need 118 symbols and names, have ' + SYMBOLS.length + ' and ' + NAMES.length);
  const rows = SYMBOLS.map((sym, i) => { const z = i + 1, [col, row] = place(z); return [z, sym, NAMES[i], col, row, family(z, col, row)]; });
  fs.writeFileSync(path.join(__dirname, '..', 'src', 'data', 'elements.js'),
    '// Element names, symbols and table positions. Generated by scripts/gen-elements.js from facts (IUPAC names and symbols,\n' +
    '// the standard 18-column layout, textbook families), not from any third-party dataset.\n' +
    'const ELEMENT_ROWS=' + JSON.stringify(rows) + ';\n');
  const counts = {}; rows.forEach(r => counts[r[5]] = (counts[r[5]] || 0) + 1);
  console.log('wrote', rows.length, 'elements', JSON.stringify(counts));
}
