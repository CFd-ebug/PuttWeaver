#!/usr/bin/env node
// Writes src/data/previews.js: one small picture per game, taken from the real engine (what the projector shows at the start of the
// game). The Manager's game picker shows them. Our own output, so there is nothing to license.
// Run `npm run build` first, then `node scripts/gen-previews.js`, then build again.
const fs = require('fs'), path = require('path');
const { chromium } = require('playwright');
const root = path.join(__dirname, '..');
(async () => {
  const browser = await chromium.launch({ executablePath: process.env.CHROMIUM_PATH || undefined, args: ['--no-sandbox', '--use-angle=swiftshader', '--enable-unsafe-swiftshader', '--ignore-gpu-blocklist'] });
  const page = await browser.newPage({ viewport: { width: 1280, height: 720 } });
  page.on('pageerror', e => { console.error('page error:', e.message); process.exit(1); });
  await page.goto('file://' + path.join(root, 'dist', 'test.html') + '#host');
  await page.waitForFunction(() => window.__lab);
  await page.evaluate(() => { __lab.enterProj(); });
  const count = JSON.parse(fs.readFileSync(path.join(root, 'src', 'games', 'games.json'), 'utf8')).length;
  const out = {};
  for (let i = 0; i < count; i++) {
    await page.evaluate(i => __lab.select(i), i);
    await page.waitForTimeout(700);
    const r = await page.evaluate(() => {
      const g = __lab.game, img = __lab.sheetPicture(400, 0.72, 16000); let tx = 0.5, ty = 0.35;
      try { const t = g.autoPutt(), len = t.frac * __lab.maxRoll(); tx = (__lab.TEE.x + Math.cos(t.angle) * len) / __lab.W; ty = (__lab.TEE.y + Math.sin(t.angle) * len) / __lab.D; } catch (e) {}
      const c = (v, a, b) => Math.min(b, Math.max(a, v)); return {id: g.id, img, tx: Math.round(c(tx, 0.06, 0.94) * 1000) / 1000, ty: Math.round(c(ty, 0.1, 0.9) * 1000) / 1000};
    });
    out[r.id] = {img: r.img, tx: r.tx, ty: r.ty};          // tx, ty: where a perfect putt would end, as a fraction of the sheet (the tile animation rolls a ball there)
    console.log(r.id, r.img.length, 'chars, target', r.tx, r.ty);
  }
  await browser.close();
  const body = '// Generated by scripts/gen-previews.js from the running engine; do not edit by hand.\nconst GAME_PREVIEWS = ' + JSON.stringify(out, null, 1) + ';\n';
  fs.writeFileSync(path.join(root, 'src', 'data', 'previews.js'), body);
  console.log('wrote src/data/previews.js,', Buffer.byteLength(body), 'bytes');
})();
